/**
 * Трудовой статус сотрудника: одно название на всю CRM.
 *
 * До этого модуля подписи жили в пяти файлах и уже разошлись: один
 * экран называл испытательный срок «Испытательный срок», другой —
 * «Стажировка», третий показывал «Активен». Человек, переходя между
 * страницами, видел три слова про одно состояние и справедливо решал,
 * что это три разных состояния.
 *
 * **Почему «Работает», а не «Активен».** «Активен» — это про учётную
 * запись: она бывает активной или отключённой. Про человека так не
 * говорят, и рядом со «Стажировкой» и «Уволен» это слово читается как
 * из другого списка. В базе значение по-прежнему `ACTIVE` — его
 * перечисляет ограничение таблицы, и менять набор значений ради подписи
 * значило бы переписывать схему из-за слова.
 *
 * **Трудовой слой — не дневной.** Здесь только «кем человек числится».
 * «В офисе», «опаздывает», «в отпуске» — это про сегодня, живёт в
 * посещаемости и в этот словарь не попадает никогда: смешать их значит
 * однажды показать «в отпуске» вместо «работает» в кадровой карточке.
 */

export type StatusTone = 'ok' | 'warn' | 'off';

/** Подпись и цвет плашки для каждого значения из базы. */
export const EMPLOYMENT_STATUS: Record<string, [title: string, tone: StatusTone]> = {
  PROBATION: ['Стажировка', 'warn'],
  ACTIVE: ['Работает', 'ok'],
  SUSPENDED: ['Отстранён', 'off'],
  TERMINATED: ['Уволен', 'off'],
  ARCHIVED: ['В архиве', 'off'],
};

/**
 * Как показать статус.
 *
 * Незнакомый код возвращается как есть: молча спрятать его хуже, чем
 * показать — пустая ячейка выглядит как потерянные данные, а не как
 * состояние, о котором интерфейс ещё не знает.
 */
export function employmentStatus(code: string | null | undefined): [string, StatusTone] {
  if (!code) return ['—', 'off'];
  return EMPLOYMENT_STATUS[code] ?? [code, 'off'];
}

/** Название статуса без цвета — для строк таблиц и подписей. */
export function employmentTitle(code: string | null | undefined): string {
  return employmentStatus(code)[0];
}

/** Числится ли человек в компании: стажируется или работает. */
export function isWorking(code: string | null | undefined): boolean {
  return code === 'ACTIVE' || code === 'PROBATION';
}

/** Идёт ли испытательный срок — от этого зависят действия в карточке. */
export function isTrainee(code: string | null | undefined): boolean {
  return code === 'PROBATION';
}
