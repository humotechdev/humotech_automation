/**
 * Последний адрес каждого раздела.
 *
 * Почти всё состояние страниц CRM живёт в адресе: вкладка, фильтры,
 * выбранный сотрудник или заявка, страница списка. Пункт меню, который
 * ведёт на голый `/requests`, это состояние выбрасывает — человек
 * возвращается в раздел и видит его сброшенным.
 *
 * Поэтому меню ведёт туда, где человек был в разделе последний раз.
 * Память — на время работы вкладки: после входа заново или
 * перезагрузки разделы открываются с чистого листа.
 */

const places = new Map<string, string>();

/** Запомнить адрес, если это адрес раздела из меню (без вложенных путей). */
export function rememberPlace(pathname: string, search: string): void {
  places.set(pathname, `${pathname}${search}`);
}

/** Куда вести пункт меню раздела `to`. */
export function placeOf(to: string): string {
  return places.get(to) ?? to;
}

export function forgetPlaces(): void {
  places.clear();
}
