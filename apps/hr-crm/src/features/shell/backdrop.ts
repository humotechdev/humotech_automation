/**
 * Фотография под интерфейсом — если она в проекте есть.
 *
 * Файла в репозитории нет, и рисовать вместо него градиент, названный
 * фотографией, здесь никто не станет: подделка под снимок хуже честного
 * отсутствия. Поэтому слой ищет файл сам.
 *
 * Положите снимок светлого офиса в `src/assets/` под именем
 * `office-backdrop.jpg` (годятся также `.jpeg`, `.png`, `.webp`) — и он
 * подхватится при следующей сборке. Ни импорт, ни разметку, ни стили
 * править не нужно: `import.meta.glob` разрешается на этапе сборки и
 * возвращает пустой набор, пока файла нет.
 *
 * Размытие, светлое наложение и то, что фотография видна между
 * панелями, задаёт `crm.css`. Здесь только адрес.
 */

const FOUND = import.meta.glob<{ default: string }>(
  '../../assets/office-backdrop.{jpg,jpeg,png,webp}',
  { eager: true },
);

const first = Object.values(FOUND)[0];

/** Значение для `background-image`, либо `null`, если снимка нет. */
export const backdropImage: string | null = first
  ? `url(${first.default})`
  : null;
