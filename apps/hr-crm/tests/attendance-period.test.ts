/**
 * Границы периода на странице посещаемости.
 *
 * Проверяется то, что легко посчитать почти правильно:
 *
 * — неделя, начатая с воскресенья и разрезавшая выходные;
 * — месяц длиной в тридцать дней в любом месяце;
 * — период, у которого начало позже конца;
 * — дата, уехавшая на сутки при переходе на летнее время.
 */

import { describe, expect, test } from 'vitest';

import {
  iso,
  lengthOf,
  isPeriodKind,
  spanOf,
  spanTitle,
} from '../src/features/attendance/period';

describe('границы периода', () => {
  test('день — это один день, а не сутки с запасом', () => {
    expect(spanOf('day', '2026-09-18')).toEqual({
      from: '2026-09-18', to: '2026-09-18',
    });
  });

  test('неделя начинается с понедельника', () => {
    // 18 сентября 2026 — пятница. Неделя, начатая с воскресенья,
    // разрезала бы выходные пополам.
    expect(spanOf('week', '2026-09-18')).toEqual({
      from: '2026-09-14', to: '2026-09-20',
    });
  });

  test('воскресенье принадлежит уходящей неделе, а не следующей', () => {
    expect(spanOf('week', '2026-09-20')).toEqual({
      from: '2026-09-14', to: '2026-09-20',
    });
  });

  test('месяц кончается своим последним числом', () => {
    expect(spanOf('month', '2026-02-10').to).toBe('2026-02-28');
    expect(spanOf('month', '2028-02-10').to).toBe('2028-02-29');
    expect(spanOf('month', '2026-09-01')).toEqual({
      from: '2026-09-01', to: '2026-09-30',
    });
  });

  test('перепутанные границы меняются местами, а не дают пустой экран', () => {
    // Обычная опечатка: человек выбрал конец раньше начала.
    expect(spanOf('range', '2026-09-18', { from: '2026-09-20', to: '2026-09-14' }))
      .toEqual({ from: '2026-09-14', to: '2026-09-20' });
  });

  test('произвольный период без границ сводится к выбранному дню', () => {
    expect(spanOf('range', '2026-09-18')).toEqual({
      from: '2026-09-18', to: '2026-09-18',
    });
  });
});

describe('длина периода', () => {
  test('считается включительно', () => {
    expect(lengthOf({ from: '2026-09-14', to: '2026-09-20' })).toBe(7);
    expect(lengthOf({ from: '2026-09-18', to: '2026-09-18' })).toBe(1);
    expect(lengthOf({ from: '2026-09-01', to: '2026-09-30' })).toBe(30);
  });

  test('переход на летнее время не добавляет и не убавляет день', () => {
    // Дата считается полднем именно поэтому: в полночь некоторых
    // поясов не существует, и `new Date` уезжает на сутки.
    expect(lengthOf({ from: '2026-03-28', to: '2026-03-30' })).toBe(3);
    expect(lengthOf({ from: '2026-10-24', to: '2026-10-26' })).toBe(3);
  });
});

describe('подпись периода', () => {
  test('день называется днём', () => {
    expect(spanTitle('day', { from: '2026-09-18', to: '2026-09-18' }))
      .toBe('18 сентября 2026');
  });

  test('неделя внутри одного месяца не повторяет месяц дважды', () => {
    expect(spanTitle('week', { from: '2026-09-14', to: '2026-09-20' }))
      .toBe('14–20 сентября 2026');
  });

  test('неделя на стыке месяцев называет оба', () => {
    expect(spanTitle('week', { from: '2026-09-28', to: '2026-10-04' }))
      .toBe('28 сентября — 4 октября 2026');
  });

  test('месяц называется месяцем, а не диапазоном чисел', () => {
    expect(spanTitle('month', { from: '2026-09-01', to: '2026-09-30' }))
      .toBe('сентября 2026');
  });
});

describe('разбор адреса', () => {
  test('чужое значение периода не проходит', () => {
    expect(isPeriodKind('week')).toBe(true);
    expect(isPeriodKind('quarter')).toBe(false);
    expect(isPeriodKind(null)).toBe(false);
  });

  test('дата пишется без часового пояса', () => {
    expect(iso(new Date(2026, 8, 5, 12))).toBe('2026-09-05');
  });
});
