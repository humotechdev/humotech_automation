def test_every_foreign_key_keeps_its_on_delete_action():
    """Django не выводит `ON DELETE` сам — его восстанавливает `core/0002`.

    Без этого прямой `DELETE` мимо ORM снёс бы историю: запрет физического
    удаления объектов со связями держится на действии в самой базе,
    а не на коллекторе Django.
    """
    with connection.cursor() as cursor:
        cursor.execute(
            """
            SELECT t.relname, c.conname, c.confdeltype, c.condeferrable
              FROM pg_constraint c
              JOIN pg_class t ON t.oid = c.conrelid
              JOIN pg_namespace n ON n.oid = t.relnamespace
             WHERE n.nspname = 'public' AND c.contype = 'f'
               AND t.relname NOT LIKE 'django_%' AND t.relname NOT LIKE 'auth_%'
            """
        )
        rows = cursor.fetchall()

    # +1 — фотография сотрудника (employees/0005), RESTRICT.
    # +6 — переписка обращений (questions/0003).
    # +1 — автор точки отметки (qr_codes/0004), SET NULL.
    # +1 — руководитель отдела (departments/0003), SET NULL.
    # +13 — ключи опросов (surveys/0002).
    # +20 — ключи ознакомления (onboarding/0002).
    assert len(rows) == 192, f"внешних ключей {len(rows)}, ожидалось 192"

    # 'a' = NO ACTION: значит, действие не задано
    without_action = [f"{t}.{n}" for t, n, kind, _ in rows if kind == "a"]
    assert not without_action, (
        f"внешние ключи без ON DELETE: {without_action[:5]}"
    )
    deferrable = [f"{t}.{n}" for t, n, _, deferred in rows if deferred]
    assert not deferrable, (
        f"отложенные внешние ключи (в эталоне их нет): {deferrable[:5]}"
    )

    actions = {"r": 0, "n": 0, "c": 0}
    for _, _, kind, _ in rows:
        actions[kind] = actions.get(kind, 0) + 1
    # +3 RESTRICT и +1 SET NULL — ключи telegram_link_invitations.
    # Ещё +3 RESTRICT и +1 SET NULL — экраны показа QR. SET NULL в обоих
    # случаях один и тот же по смыслу: учётную запись сотрудника HR можно
    # заблокировать, но запись о том, что он что-то создал, обязана остаться.
    # 113 + 2 — организация и автор у задания на выгрузку.
    # 115 + 1 — попытка отправки ссылается на уведомление: удалить строку,
    # за которой стоят состоявшиеся отправки, нельзя.
    # 116 + 6 — ключи чек-листа документов и ключа приёма. Все RESTRICT:
    # чек-лист — часть кадровой истории, а ключ — единственное
    # доказательство того, что этот приём уже состоялся.
    # 122 + 1 — фотография сотрудника (employees/0005). Тоже RESTRICT:
    # файл, на который смотрит живая карточка, удаляет сервис, а не каскад.
    # 123 + 2 RESTRICT, 16 + 3 SET NULL, 6 + 1 CASCADE — переписка
    # обращений: организация и автор-сотрудник держат историю, учётная
    # запись HR и строка очереди — нет, сообщения живут с обращением.
    # 125 + 1 RESTRICT, 7 + 1 CASCADE — организация и владелец шаблона
    # отчёта: шаблон — личная настройка и уходит вместе с учётной записью.
    # 127 + 11 — ключи опросов, кроме двух авторских: шаблон с ответами,
    # рассылку с получателями и вопрос, на который ответили, удалить нельзя.
    # 140 + 16 — ключи ознакомления, кроме четырёх авторских: организация,
    # сотрудник, программа, карточка, документ, редакция и файл держат
    # историю — под подтверждением стоят имя и время.
    assert actions["r"] == 156, f"RESTRICT: {actions['r']}, ожидалось 156"
    # 19 + 1 SET NULL — автор точки отметки: учётную запись HR можно
    # отключить, а точка у двери работать не перестаёт.
    # 20 + 2 — авторы шаблона и рассылки опроса: учётную запись HR можно
    # отключить, а опрос от этого не исчезает.
    # 22 + 1 — руководитель отдела: отдел переживает своего руководителя.
    # 23 + 4 — авторы программы, прогресса, документа и публикатор
    # редакции: учётную запись кадровика можно отключить, а ознакомление
    # и выпущенный документ от этого не исчезают.
    assert actions["n"] == 27, f"SET NULL: {actions['n']}, ожидалось 27"
    assert actions["c"] == 9, f"CASCADE: {actions['c']}, ожидалось 9"
