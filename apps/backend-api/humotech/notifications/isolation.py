"""Предохранители против синтетических уведомлений в рабочей базе.

Однажды посев проверочных строк сделали скриптом по рабочей базе. Скрипт
отработал безупречно, и две выдуманные строки ушли настоящим людям в
Telegram: рядом работал настоящий отправщик. Предупреждение в
документации в тот момент тоже было.

Отсюда правило: место, где заводятся синтетические уведомления, обязано
САМО отказываться работать в рабочем окружении. Здесь собраны три
проверки, и каждой достаточно поодиночке:

  1. переменная окружения. Её ставят только в изолированном стенде;
  2. имя базы. Разрешены `test_*` и `*_e2e` — списком разрешённого, а не
     запретом рабочего имени: запрет ломается в день, когда рядом
     появляется вторая рабочая база;
  3. адресаты. База, где есть привязка Telegram с настоящим chat id, —
     это база с настоящими получателями, как бы она ни называлась.

Третью проверку нельзя написать как «нет ни одной привязки»: сквозной
сценарий очереди без адресата не проходит вовсе — `claim` снимает такую
строку как `not_linked`, и доставка не проверяется. Поэтому у стенда есть
СВОЙ диапазон идентификаторов чатов, заведомо не встречающийся у людей.
"""

from __future__ import annotations

import os
import re

from django.core.management.base import CommandError
from django.db import connection

ENV_MARKER = "HUMOTECH_TEST_STAND"

# Имя базы должно СОВПАСТЬ с образцом. Неизвестное имя — рабочее.
ALLOWED_DATABASE = re.compile(r"^test_|_e2e$")

# Диапазон идентификаторов чатов изолированного стенда. Настоящие
# идентификаторы Telegram в него не попадают: даже у самых первых
# аккаунтов они пятизначные и больше, а отрицательные принадлежат
# группам и каналам — то есть тоже настоящим адресатам.
E2E_CHAT_ID_FLOOR = 1
E2E_CHAT_ID_CEILING = 1000


#: Диапазон демонстрационных привязок (`seed_demo_hr_data`). Отдельный
#: от диапазона стенда: сквозные проверки доставки ходят в свой, а в этот
#: не уходит ничего — очередь снимает такие сообщения, не отдавая боту.
#: Витрину показывают директору, кнопки в ней нажимают по-настоящему, и
#: «Напомнить всем» на сто девяносто человек не должно достучаться ни до
#: кого живого.
DEMO_CHAT_ID_FLOOR = 5000
DEMO_CHAT_ID_CEILING = 6000


def is_demo_chat_id(chat_id: int) -> bool:
    """Принадлежит ли идентификатор чата демонстрационной витрине."""
    return DEMO_CHAT_ID_FLOOR <= chat_id < DEMO_CHAT_ID_CEILING


def is_stand_chat_id(chat_id: int) -> bool:
    """Принадлежит ли идентификатор чата диапазону стенда."""
    return E2E_CHAT_ID_FLOOR <= chat_id < E2E_CHAT_ID_CEILING


def require_isolated_stand() -> None:
    """Отказать, если это не изолированный стенд. Три независимые причины."""
    # Импорт внутри: модуль читается и в контексте, где приложения ещё
    # не загружены (проверка настроек), а модель нужна только здесь.
    from humotech.telegram.models import TelegramAccount

    if os.environ.get(ENV_MARKER) != "1":
        raise CommandError(
            f"Нужна переменная окружения {ENV_MARKER}=1. Она ставится "
            "только в изолированном стенде: без неё команда считает базу "
            "рабочей и ничего не заводит."
        )

    name = connection.settings_dict.get("NAME") or ""
    if not ALLOWED_DATABASE.search(name):
        raise CommandError(
            f"База «{name}» не похожа на тестовую. Разрешены только имена "
            "вида test_* и *_e2e: рабочую базу синтетическими "
            "уведомлениями не наполняют."
        )

    outsiders = [
        chat_id
        for chat_id in TelegramAccount.objects.filter(
            status="ACTIVE"
        ).values_list("telegram_chat_id", flat=True)
        if not is_stand_chat_id(chat_id)
    ]
    if outsiders:
        raise CommandError(
            f"В базе {len(outsiders)} действующих привязок Telegram с "
            "настоящими идентификаторами чатов. Это живые адресаты: "
            "синтетическое уведомление здесь может уйти человеку. "
            "Команда остановлена."
        )


__all__ = [
    "ALLOWED_DATABASE",
    "E2E_CHAT_ID_CEILING",
    "E2E_CHAT_ID_FLOOR",
    "DEMO_CHAT_ID_CEILING",
    "DEMO_CHAT_ID_FLOOR",
    "is_demo_chat_id",
    "ENV_MARKER",
    "is_stand_chat_id",
    "require_isolated_stand",
]
