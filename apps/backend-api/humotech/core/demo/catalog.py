@dataclass(frozen=True)
class DemoOffice:
    """Один офис витрины и его состав на опорный день.

    `staff` — сколько человек всего. Остальные четыре — сколько из них в
    каком состоянии. Пятое состояние, «отметился и ушёл», не задаётся:
    оно остаток, и считать его отдельно значило бы завести число, которое
    может разойтись с суммой.

    `discipline` сдвигает поведение всего офиса: отрицательное значение —
    приходят собраннее, положительное — чаще опаздывают. Нужно, чтобы
    сравнение офисов в аналитике показывало разницу, а не двенадцать
    одинаковых столбиков.
    """

    code: str
    region: str
    name: str
    city: str
    address: str
    staff: int
    in_office: int
    not_come: int
    vacation: int
    sick: int
    #: Сдвиг дисциплины в минутах: прибавляется к типичному отклонению.
    discipline: int = 0
    #: Координаты центра города, где стоит офис. Настоящие: по ним офис
    #: ставится на карту и строится геозона. Адрес при этом вымышленный —
    #: точка офиса совпадает с центром города, а не с конкретным зданием.
    latitude: float | None = None
    longitude: float | None = None

    @property
    def left(self) -> int:
        return self.staff - self.in_office - self.not_come - self.vacation - self.sick

    @property
    def big(self) -> bool:
        """Крупный офис: у него больше отделов и несколько точек отметки."""
        return self.staff >= 20


