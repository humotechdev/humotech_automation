    #: считать его опоздавшим значило бы показать больше половины
    #: компании нарушителями каждый день.
    late_grace: int = 15
    early_leave_grace: int = 10
    flexible: bool = False
    #: Доля сотрудников, которым назначается этот график.
    share: int = 0


