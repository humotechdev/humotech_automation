@dataclass(frozen=True)
class DemoSchedule:
    """Один график витрины.

    `weekly_minutes` — договорное недельное время БЕЗ обеда. По нему
    считается дневная норма (`weekly_minutes / рабочие дни`), и именно
    так её считает backend: разница между концом и началом смены сюда не
    годится, в неё попадает обед.
    """

    code: str
    name: str
    weekdays: tuple[int, ...]
    start: time
    end: time
    #: Обед. `None` — графика обеда нет (неполный день).
    lunch: tuple[time, time] | None
