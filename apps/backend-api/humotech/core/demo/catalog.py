    code: str
    #: Типичное отклонение прихода от начала смены, минуты (от, до).
    arrival: tuple[int, int]
    #: Отклонение ухода от конца смены, минуты (от, до).
    departure: tuple[int, int]
    #: Доля дней без отметки вовсе, в процентах.
    absent_pct: int
    share: int


