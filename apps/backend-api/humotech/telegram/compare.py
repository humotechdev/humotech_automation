"""Сравнение секретов, пришедших от клиента.

`hmac.compare_digest` не принимает строки с символами вне ASCII: он бросает
`TypeError`. А секрет и подпись приходят из заголовка и query-строки, то есть
их содержимое выбирает отправитель. Прямой вызов означал бы, что запрос
с кириллицей в заголовке даёт 500 вместо честного отказа — и заодно строчку
в журнале с чужим содержимым вместо тихого «не подошло».

Поэтому обе стороны сначала хешируются:

  * сравниваются всегда 32 байта, что бы ни пришло на вход. Длина секрета
    не утекает через быстрый отказ на несовпадении длин;
  * любые байты допустимы, включая не-ASCII и пустую строку;
  * само сравнение остаётся постоянным по времени — обычное `==` выходит
    на первом несовпавшем байте, и по времени ответа секрет подбирается
    посимвольно.
"""

from __future__ import annotations

import hashlib
import hmac


def constant_time_equal(supplied: str | bytes, expected: str | bytes) -> bool:
    """Совпадают ли два секрета. Время выполнения от содержимого не зависит."""
    return hmac.compare_digest(_digest(supplied), _digest(expected))


def _digest(value: str | bytes) -> bytes:
    raw = value.encode("utf-8") if isinstance(value, str) else value
    return hashlib.sha256(raw).digest()
