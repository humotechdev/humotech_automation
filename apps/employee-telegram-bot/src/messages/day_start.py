"""Тексты ответа на напоминание о начале дня.

Отдельно от обработчика: формулировки правят чаще, чем логику, и
держать их в файле с разбором нажатий — способ задеть второе, правя
первое.

Главное правило этих текстов: не обещать того, чего не произошло.
«Не приду» не открывает больничный и не оформляет отпуск, и человек
должен уйти из этого разговора, зная, что заявку ещё нужно подать.
"""

from __future__ import annotations

from aiogram.types import InlineKeyboardButton, InlineKeyboardMarkup

#: Код нажатия «без причины».
SKIP = "day:skip"

ASK_LATE_REASON = (
    "Понял. Напишите одной строкой, что случилось, — или нажмите "
    "«Без причины»."
)
ASK_ABSENT_REASON = (
    "Понял. Напишите коротко, почему вас не будет, — или нажмите "
    "«Без причины»."
)
REASON_EMPTY = "Нужен текст одной строкой. Или нажмите «Без причины»."

LATE_SAVED = "Хорошо, информация передана администратору."
ABSENT_SAVED = (
    "Хорошо, информация передана администратору.\n\n"
    "Если причина — отпуск или больничный, пожалуйста, оформите заявку "
    "в Mini App: без заявки отсутствие остаётся неоформленным."
)
FAILED = "Не получилось передать. Попробуйте ещё раз через пару минут."

MARK_HINT = (
    "Откройте кабинет кнопкой «📷 Отметиться» и отсканируйте код у входа."
)


def skip_markup() -> InlineKeyboardMarkup:
    """Кнопка «Без причины».

    Она есть намеренно: требовать объяснение у того, кто стоит в пробке,
    — способ не получить ни объяснения, ни предупреждения.
    """
    return InlineKeyboardMarkup(
        inline_keyboard=[[
            InlineKeyboardButton(text="Без причины", callback_data=SKIP)
        ]]
    )


